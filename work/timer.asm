; Μετρητής στη θύρα εξόδου με καθυστέρηση από τον timer.
;
; WAIT 1  = 1.024 παλμοί  : μικρή καθυστέρηση, για την προσομοίωση
; (ο timer τρέχει μόνο μέσα στο WAIT, για οικονομία ρεύματος)
; WAIT 13 = 4.194.304 παλμοί = 0,42 s στα 10 MHz : για αληθινά LED
;
        LOAD 0
loop:   OUT             ; γράψε τον A στη θύρα εξόδου
        WAIT 1          ; περίμενε έναν χτύπο του timer
        ADD 1           ; επόμενο νούμερο
        JUMP loop
